"""Kết nối PostgreSQL, base model và mixin dùng chung."""

from collections.abc import AsyncIterator, Iterator
from contextlib import contextmanager
from datetime import datetime
from functools import lru_cache
from typing import Annotated

from sqlalchemy import BigInteger, DateTime, Engine, Identity, MetaData, create_engine, func
from sqlalchemy.engine import URL, make_url
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase, Mapped, Session, mapped_column

from app.core.config import get_settings
from app.core.constants import DB_CONNECT_TIMEOUT_SECONDS
from app.core.exceptions import AppError

# Driver đồng bộ cho Celery worker (docs/architecture.md, quyết định 3).
SYNC_DRIVER = "postgresql+psycopg"

# Khóa chính bigint tự tăng (GENERATED BY DEFAULT AS IDENTITY).
BigIntPK = Annotated[int, mapped_column(BigInteger, Identity(), primary_key=True)]

# Đặt tên constraint, index cố định để migration autogenerate ổn định giữa các máy.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class TimestampMixin(CreatedAtMixin):
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class SoftDeleteMixin:
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), default=None)


engine = create_async_engine(
    get_settings().database_url,
    pool_pre_ping=True,
    connect_args={"timeout": DB_CONNECT_TIMEOUT_SECONDS},
)
SessionFactory = async_sessionmaker(engine, expire_on_commit=False)


async def get_db_session() -> AsyncIterator[AsyncSession]:
    async with SessionFactory() as session:
        yield session


def sync_database_url(url: str) -> URL:
    """Cùng database với `url` (asyncpg của API), đổi sang driver đồng bộ psycopg."""
    return make_url(url).set(drivername=SYNC_DRIVER)


@lru_cache
def get_sync_engine() -> Engine:
    """Engine đồng bộ cho Celery worker, tạo ở lần dùng đầu.

    Không tạo lúc import: worker prefork fork process con sau khi nạp code, kết nối mở ở process
    cha mà dùng chung cho các process con thì hỏng. Task chạy trong process con nên mỗi process
    tự tạo engine của mình. API không dùng engine này.
    """
    return create_engine(
        sync_database_url(get_settings().database_url),
        pool_pre_ping=True,
        connect_args={"connect_timeout": DB_CONNECT_TIMEOUT_SECONDS},
    )


@contextmanager
def sync_session() -> Iterator[Session]:
    """Session đồng bộ cho Celery task: task chạy đồng bộ, không chạy event loop bên trong."""
    with Session(get_sync_engine(), expire_on_commit=False) as session:
        yield session


async def commit_unique(session: AsyncSession, constraint: str, error: AppError) -> None:
    """Commit; vi phạm unique `constraint` thì rollback và ném `error` thay cho lỗi 500.

    Service vẫn kiểm tra trùng trước để báo lỗi sớm, nhưng hai request song song cùng qua được
    bước kiểm tra đó, request commit sau chỉ bị DB chặn ở đây.
    """
    try:
        await session.commit()
    except IntegrityError as exc:
        await session.rollback()
        # asyncpg gắn lỗi gốc (UniqueViolationError, có constraint_name) làm __cause__ của lỗi
        # DBAPI mà SQLAlchemy bọc lại; so tên thay vì tìm chuỗi trong message.
        cause = getattr(exc.orig, "__cause__", None)
        if getattr(cause, "constraint_name", None) == constraint:
            raise error from exc
        raise
